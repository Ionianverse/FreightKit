#!/usr/bin/env python3
"""Build assets/js/search-index.js for the site-wide search (header button, "/" or Ctrl+K).

It lists every public, indexable page (title, description, link, kind) and every template
download from templates/index.html. Run it after adding or renaming a page or template:

    python scripts/build-search-index.py
"""
from pathlib import Path
import html
import json
import re

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets' / 'js' / 'search-index.js'
PRIVATE = {'.git', 'docs', 'bo-src', 'sample', 'samples', '.claude', 'downloads', 'assets', 'scripts'}
SKIP = {'404.html', 'contact-success/index.html', 'embed/index.html', 'tools/custom-calculator/index.html', 'tools/bo-remarks/index.html'}
ROOT_TOOLS = {'document-process/', 'bo-planning/', 'custom-calculator/'}  # the page itself is the tool
KIND = [('tools/', 'Tool'), ('guides/', 'Guide'), ('document-process/', 'Workflow'), ('bo-planning/', 'Private tool'), ('custom-calculator/', 'Tool')]
# Clearer names in search for pages whose title is generic.
TITLES = {'document-process/': 'Freight Invoice Review (Document Review)'}
# Extra words people search for that are not always in the title or description.
EXTRA = {
    'tools/volumetric-weight/': 'chargeable weight air freight divisor dim',
    'tools/cbm-calculator/': 'cubic metre volume carton',
    'tools/freight-invoice-audit/': 'invoice audit overcharge quote',
    'document-process/': 'invoice review audit quote pdf excel overcharge',
    'tools/po-exception-report/': 'purchase order eta late overdue',
    'tools/safety-stock/': 'reorder point rop',
    'tools/customs-duty-estimator/': 'import tax gst vat',
    'bo-planning/': 'back order backorder planning expedite',
    'services/': 'custom tool automation spreadsheet excel consulting build',
}


def clean(text):
    text = re.sub(r'<[^>]+>', ' ', text or '')
    return re.sub(r'\s+', ' ', html.unescape(text)).strip()


def pages():
    out = []
    for page in sorted(ROOT.rglob('index.html')):
        rel = page.relative_to(ROOT).as_posix()
        if PRIVATE.intersection(page.relative_to(ROOT).parts) or rel in SKIP:
            continue
        text = page.read_text(encoding='utf-8')
        if 'noindex' in text and not rel.startswith('bo-planning/'):
            continue
        title = clean((re.search(r'<title>(.*?)</title>', text, re.S) or [None, ''])[1])
        title = re.sub(r'\s*[|—–-]\s*FreightKit.*$', '', title).strip() or 'FreightKit'
        desc = clean((re.search(r'<meta name="description" content="([^"]*)"', text) or [None, ''])[1])
        url = rel[:-len('index.html')]
        title = TITLES.get(url, title)
        kind = next((k for prefix, k in KIND if url.startswith(prefix) and (url != prefix or prefix in ROOT_TOOLS)), 'Page')
        if url == 'tools/':
            kind = 'Page'
        out.append({'t': title, 'd': desc, 'u': url, 'k': kind, 'x': EXTRA.get(url, '')})
    return out


def templates():
    text = (ROOT / 'templates' / 'index.html').read_text(encoding='utf-8')
    out = []
    for card in re.findall(r'<div class="card toolcard template-card">(.*?)</div>', text, re.S):
        title = clean((re.search(r'<h3>(.*?)</h3>', card, re.S) or [None, ''])[1])
        desc = clean((re.search(r'</h3>\s*<p>(.*?)</p>', card, re.S) or [None, ''])[1])
        link = re.search(r'href="\.\./(downloads/[^"]+)"', card)
        badge = clean((re.search(r'<span class="badge">(.*?)</span>', card, re.S) or [None, ''])[1])
        if title and link:
            fmt = 'Excel' if link.group(1).endswith('.xlsx') else 'CSV'
            out.append({'t': title, 'd': desc, 'u': link.group(1), 'k': f'Template ({fmt})', 'x': badge})
    return out


def main():
    items = pages() + templates()
    body = json.dumps(items, ensure_ascii=False, separators=(',', ':'))
    OUT.write_text('/* Generated by scripts/build-search-index.py; do not edit by hand. */\n'
                   f'window.FK_SEARCH_INDEX={body};\n', encoding='utf-8')
    kinds = {}
    for i in items:
        kinds[i['k']] = kinds.get(i['k'], 0) + 1
    print(f'Wrote {OUT.relative_to(ROOT)}: {len(items)} entries ' + ', '.join(f'{k} {n}' for k, n in sorted(kinds.items())))


if __name__ == '__main__':
    main()
